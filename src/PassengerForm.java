    private void btnInsertActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertActionPerformed
        // TODO add your handling code here:
        // Step 1: Validate input first
    if (
        txtName.getText().trim().isEmpty() ||
        txtPassport.getText().trim().isEmpty() ||
        txtNationality.getText().trim().isEmpty() ||
        txtDOB.getText().trim().isEmpty() ||
        txtFlight.getText().trim().isEmpty() ||
        txtSeat.getText().trim().isEmpty()
    ) {
        JOptionPane.showMessageDialog(this, "Please fill in all the fields.");
        return;
    }

    // Step 2: Get input values
    String name = txtName.getText();
    String passport = txtPassport.getText();
    String nationality = txtNationality.getText();
    String gender = comboGender.getSelectedItem().toString();
    String dob = txtDOB.getText();
    String flightNo = txtFlight.getText();
    String seatNo = txtSeat.getText();
   int checkIn = chkCheckIn.isSelected() ? 1 : 0;

    // Step 3: Prepare SQL query
    String sql = "INSERT INTO passengers (name, passport_number, nationality, gender, date_of_birth, flight_number, seat_number, check_in_status) VALUES (?, ?, ?, ?, ?, ?, ?, ?)";

    // Step 4: Try inserting into DB
    try {
        Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/airport_db", "root", "");

        PreparedStatement pstmt = conn.prepareStatement(sql);
        pstmt.setString(1, name);
        pstmt.setString(2, passport);
        pstmt.setString(3, nationality);
        pstmt.setString(4, gender);
        pstmt.setDate(5, java.sql.Date.valueOf(dob));  // Format: yyyy-MM-dd
        pstmt.setString(6, flightNo);
        pstmt.setString(7, seatNo);
        pstmt.setInt(8, checkIn);

        int rowsInserted = pstmt.executeUpdate();

        if (rowsInserted > 0) {
            JOptionPane.showMessageDialog(this, "Passenger inserted successfully!");
            
            loadPassengerData();  // Refresh the table after insert
            

        }

        pstmt.close();
        conn.close();
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Insert Error: " + e.getMessage());
    }



    }//GEN-LAST:event_btnInsertActionPerformed

