    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        
    try {
        Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/airport_db", "root", "");

        String sql = "UPDATE passengers SET name = ?, nationality = ?, gender = ?, date_of_birth = ?, flight_number = ?, seat_number = ?, check_in_status = ? WHERE passport_number = ?";

        PreparedStatement pstmt = conn.prepareStatement(sql);

        // Setting values from input fields
        pstmt.setString(1, txtName.getText());
        pstmt.setString(2, txtNationality.getText());
        pstmt.setString(3, comboGender.getSelectedItem().toString());

        // Parse date safely
        try {
            java.sql.Date dob = java.sql.Date.valueOf(txtDOB.getText()); // Format: yyyy-MM-dd
            pstmt.setDate(4, dob);
        } catch (IllegalArgumentException ex) {
            JOptionPane.showMessageDialog(this, "Invalid date format. Use yyyy-MM-dd.");
            conn.close();
            return;
        }

        pstmt.setString(5, txtFlight.getText());
        pstmt.setString(6, txtSeat.getText());
        pstmt.setBoolean(7, chkCheckIn.isSelected());

        pstmt.setString(8, txtPassport.getText()); // WHERE clause

        // Execute update
        int rows = pstmt.executeUpdate();
        if (rows > 0) {
            JOptionPane.showMessageDialog(this, "Passenger updated successfully!");
            loadPassengerData();
}
        else{
            JOptionPane.showMessageDialog(this, "No Passenger found with this passport number");
            
}

        conn.close();
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error: " + e.getMessage());
    }

    }//GEN-LAST:event_btnUpdateActionPerformed

