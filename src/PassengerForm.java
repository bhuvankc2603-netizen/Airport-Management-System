    private void loadPassengerData() {
    try {
        Connection conn = DriverManager.getConnection("jdbc:mysql://localhost:3306/airport_db", "root", "");

        String sql = "SELECT * FROM passengers";
        PreparedStatement pstmt;
        pstmt = conn.prepareStatement(sql);
        ResultSet rs = pstmt.executeQuery();

        // Create table model with column names
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("Name");
        model.addColumn("Passport No");
        model.addColumn("Nationality");
        model.addColumn("Gender");
        model.addColumn("DOB");
        model.addColumn("Flight No");
        model.addColumn("Seat No");
        model.addColumn("Check-In");

        // Fill model with data from ResultSet
        while (rs.next()) {
            model.addRow(new Object[]{
                rs.getString("name"),
                rs.getString("passport_number"),
                rs.getString("nationality"),
                rs.getString("gender"),
                rs.getDate("date_of_birth"),
                rs.getString("flight_number"),
                rs.getString("seat_number"),
                rs.getBoolean("check_in_status") ? "Yes" : "No"
            });
        }

        // Set model to JTable
        tablePassengers.setModel(model);

        conn.close();
    } catch (Exception e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error loading data: " + e.getMessage());
    }
}

